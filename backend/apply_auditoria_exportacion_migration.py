"""
apply_auditoria_exportacion_migration.py
Crea la tabla 'auditoria_exportacion' para registrar cada exportación de datos
(Libro de Matrícula PDF/Excel y reporte Excel de matrículas): quién, con qué rol,
de qué establecimiento, con qué filtros, en qué formato y cuántos registros.

Por qué una tabla aparte: 'auditoria_matricula' exige un id_matricula, y una
exportación masiva no corresponde a una matrícula puntual.

Solo AGREGA una tabla nueva (no toca datos existentes). Idempotente.
DRY-RUN por defecto; exige --apply para escribir.

Uso (desde backend/):
    python apply_auditoria_exportacion_migration.py           # DRY-RUN
    python apply_auditoria_exportacion_migration.py --apply   # crea la tabla
"""
import sys
import os

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from database import get_db_connection

DDL = """
CREATE TABLE IF NOT EXISTS auditoria_exportacion (
    id_exportacion      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario          INTEGER NULL,
    correo_usuario      VARCHAR(150) NULL,
    rol_usuario         VARCHAR(60) NULL,
    id_establecimiento  INTEGER NULL,
    tipo_exportacion    VARCHAR(60) NOT NULL,
    formato             VARCHAR(10) NOT NULL,
    filtros             JSONB NULL,
    cantidad_registros  INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_auditoria_exportacion_fecha ON auditoria_exportacion (fecha);
CREATE INDEX IF NOT EXISTS idx_auditoria_exportacion_est ON auditoria_exportacion (id_establecimiento);
"""


def migrate(aplicar: bool):
    conn = get_db_connection()
    cur = conn.cursor()
    try:
        cur.execute("""
            SELECT 1 FROM information_schema.tables
            WHERE table_schema = current_schema() AND table_name = 'auditoria_exportacion';
        """)
        if cur.fetchone():
            print("[OK] La tabla auditoria_exportacion ya existe. Nada que hacer.")
            return
        print("[FALTA] Tabla auditoria_exportacion.")
        if not aplicar:
            print("DRY-RUN: no se escribió nada. Ejecute con --apply para crearla.")
            return
        cur.execute(DDL)
        conn.commit()
        print("Tabla auditoria_exportacion creada.")
    except Exception as e:
        conn.rollback()
        print(f"Error durante la migración: {e}")
        raise
    finally:
        cur.close()
        conn.close()


if __name__ == "__main__":
    migrate(aplicar="--apply" in sys.argv)
